/// 柿の印の実（塗りは --kaki-soft、線は --kaki）。
public struct BrandFruitShape: Shape {
  public static let size = CGSize(width: 48, height: 48)
  public init() {}
  public func path(in rect: CGRect) -> Path {
    let scale = min(rect.width / Self.size.width, rect.height / Self.size.height)
    let dx = rect.minX + (rect.width - Self.size.width * scale) / 2
    let dy = rect.minY + (rect.height - Self.size.height * scale) / 2
    func p(_ x: CGFloat, _ y: CGFloat) -> CGPoint { CGPoint(x: dx + x * scale, y: dy + y * scale) }
    var path = Path()
    path.move(to: p(24, 4))
    path.addCurve(to: p(40, 25), control1: p(31, 12), control2: p(40, 14))
    path.addCurve(to: p(24, 42), control1: p(40, 34), control2: p(33, 42))
